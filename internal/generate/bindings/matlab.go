package bindings

import (
	"os"
	"strings"

	toolspec "github.com/hydrocode-de/tool-spec-go"
)

type MatlabGenerator struct{}

func (g *MatlabGenerator) Generate(spec toolspec.ToolSpec, outputPath string) error {
	_ = spec
	var buf strings.Builder
	buf.WriteString("% AUTO-GENERATED by gotap - do not edit\n\n")

	buf.WriteString("function [params, data] = get_parameters(input_file, spec_file)\n")
	buf.WriteString("% get_parameters Parse tool input using gotap\n")
	buf.WriteString("%   Returns params struct with parameter values and data struct with file paths\n")
	buf.WriteString("    if nargin < 1\n")
	buf.WriteString("        input_file = '/in/input.json';\n")
	buf.WriteString("    end\n")
	buf.WriteString("    if nargin < 2\n")
	buf.WriteString("        spec_file = '/src/tool.yml';\n")
	buf.WriteString("    end\n")
	buf.WriteString("    json_data = load_input(input_file, spec_file);\n")
	buf.WriteString("    params = json_data.parameters;\n")
	buf.WriteString("    data = json_data.data;\n")
	buf.WriteString("end\n")
	buf.WriteString("\n")
	buf.WriteString("function json_data = load_input(input_file, spec_file)\n")
	buf.WriteString("    [status, result] = system(['gotap parse --input-file ' input_file ' --spec-file ' spec_file]);\n")
	buf.WriteString("    if status ~= 0\n")
	buf.WriteString("        error('gotap parse failed: %s', result);\n")
	buf.WriteString("    end\n")
	buf.WriteString("    json_data = jsondecode(result);\n")
	buf.WriteString("end\n")
	buf.WriteString("\n")
	buf.WriteString("function context = get_run_context()\n")
	buf.WriteString("    context.run_id = getenv('GOTAP_RUN_ID');\n")
	buf.WriteString("    context.log_file = getenv('GOTAP_LOG_FILE');\n")
	buf.WriteString("    context.log_format = getenv('GOTAP_LOG_FORMAT');\n")
	buf.WriteString("    if isempty(context.log_format)\n")
	buf.WriteString("        context.log_format = 'jsonl';\n")
	buf.WriteString("    end\n")
	buf.WriteString("    context.log_level = getenv('GOTAP_LOG_LEVEL');\n")
	buf.WriteString("    if isempty(context.log_level)\n")
	buf.WriteString("        context.log_level = 'info';\n")
	buf.WriteString("    end\n")
	buf.WriteString("end\n")
	buf.WriteString("\n")
	buf.WriteString("function logger = get_logger()\n")
	buf.WriteString("    context = get_run_context();\n")
	buf.WriteString("    logger.log = @(level, event, message, fields) write_log(context, level, event, message, fields);\n")
	buf.WriteString("    logger.debug = @(event, message, varargin) write_level_log(context, 'debug', event, message, varargin{:});\n")
	buf.WriteString("    logger.info = @(event, message, varargin) write_level_log(context, 'info', event, message, varargin{:});\n")
	buf.WriteString("    logger.warn = @(event, message, varargin) write_level_log(context, 'warn', event, message, varargin{:});\n")
	buf.WriteString("    logger.error = @(event, message, varargin) write_level_log(context, 'error', event, message, varargin{:});\n")
	buf.WriteString("end\n")
	buf.WriteString("\n")
	buf.WriteString("function write_level_log(context, level, event, message, varargin)\n")
	buf.WriteString("    fields = struct();\n")
	buf.WriteString("    if ~isempty(varargin)\n")
	buf.WriteString("        fields = varargin{1};\n")
	buf.WriteString("    end\n")
	buf.WriteString("    write_log(context, level, event, message, fields);\n")
	buf.WriteString("end\n")
	buf.WriteString("\n")
	buf.WriteString("function write_log(context, level, event, message, fields)\n")
	buf.WriteString("    if nargin < 5\n")
	buf.WriteString("        fields = struct();\n")
	buf.WriteString("    end\n")
	buf.WriteString("    payload = struct('ts', char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...\n")
	buf.WriteString("        'level', level, 'event', event, 'message', message, 'run_id', context.run_id);\n")
	buf.WriteString("    names = fieldnames(fields);\n")
	buf.WriteString("    for i = 1:numel(names)\n")
	buf.WriteString("        payload.(names{i}) = fields.(names{i});\n")
	buf.WriteString("    end\n")
	buf.WriteString("    line = [jsonencode(payload) newline];\n")
	buf.WriteString("    if ~isempty(context.log_file)\n")
	buf.WriteString("        fid = fopen(context.log_file, 'a');\n")
	buf.WriteString("        if fid == -1\n")
	buf.WriteString("            error('could not open log file: %s', context.log_file);\n")
	buf.WriteString("        end\n")
	buf.WriteString("        cleaner = onCleanup(@() fclose(fid));\n")
	buf.WriteString("        fprintf(fid, '%s', line);\n")
	buf.WriteString("    else\n")
	buf.WriteString("        fprintf(2, '%s', line);\n")
	buf.WriteString("    end\n")
	buf.WriteString("end\n")

	return os.WriteFile(outputPath, []byte(buf.String()), 0644)
}
